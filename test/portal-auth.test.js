const fs = require("fs");
const path = require("path");
const { createClient } = require("@supabase/supabase-js");

// Read .env.local
const envFile = fs.readFileSync(path.join(__dirname, "../.env.local"), "utf8");
const envVars = {};
envFile.split("\n").forEach((line) => {
  const idx = line.indexOf("=");
  if (idx > -1) {
    const k = line.slice(0, idx).trim();
    let v = line.slice(idx + 1).trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
      v = v.slice(1, -1);
    }
    if (k) envVars[k] = v;
  }
});

const SUPABASE_URL = envVars.NEXT_PUBLIC_SUPABASE_URL;
const SUPABASE_ANON_KEY =
  envVars.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY ||
  envVars.NEXT_PUBLIC_SUPABASE_ANON_KEY;

const DEMO_CLIENT_EMAIL = envVars.DEMO_CLIENT_EMAIL || "demo.client@nyay.live";
const DEMO_CLIENT_PASSWORD = envVars.DEMO_CLIENT_PASSWORD || "NyayLink#DemoClient2026!";
const DEMO_LAWYER_EMAIL = envVars.DEMO_LAWYER_EMAIL || "demo.lawyer@nyay.live";
const DEMO_LAWYER_PASSWORD = envVars.DEMO_LAWYER_PASSWORD || "NyayLink#DemoLawyer2026!";
const BASE_URL = process.env.TEST_BASE_URL || "http://localhost:3000";

console.log("======================================================================");
console.log(">>> NYAYLINK PORTAL & DEMO ACCOUNT VERIFICATION TEST SUITE <<<");
console.log("======================================================================");

async function runPortalTests() {
  let passed = 0;
  let failed = 0;

  function assert(cond, desc, details) {
    if (cond) {
      passed++;
      console.log(`  ✓ [PASS] ${desc}`);
    } else {
      failed++;
      console.error(`  ❌ [FAIL] ${desc} — ${details || "Assertion failed"}`);
    }
  }

  // 1. Unauthenticated Route Protection
  console.log("\n[Test 1/6] Testing Unauthenticated Visitor Access Redirections...");
  try {
    const resClient = await fetch(`${BASE_URL}/dashboard`, { redirect: "manual" });
    assert(
      resClient.status === 307 || resClient.status === 302,
      "Unauthenticated /dashboard redirects to login",
      `Status: ${resClient.status}`
    );

    const resLawyer = await fetch(`${BASE_URL}/lawyer/dashboard`, { redirect: "manual" });
    assert(
      resLawyer.status === 307 || resLawyer.status === 302,
      "Unauthenticated /lawyer/dashboard redirects to login",
      `Status: ${resLawyer.status}`
    );

    const resAdmin = await fetch(`${BASE_URL}/admin/dashboard`, { redirect: "manual" });
    assert(
      resAdmin.status === 307 || resAdmin.status === 302,
      "Unauthenticated /admin/dashboard redirects to login",
      `Status: ${resAdmin.status}`
    );
  } catch (err) {
    assert(false, "Route protection check failed", err.message);
  }

  // 2. Demo Login API Route (Server-Side SSR Auth Cookie Handler)
  console.log("\n[Test 2/6] Testing /api/auth/demo-login endpoint...");
  try {
    const clientDemoRes = await fetch(`${BASE_URL}/api/auth/demo-login`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ role: "client" }),
    });
    const clientDemoData = await clientDemoRes.json();
    const clientCookies = clientDemoRes.headers.get("set-cookie");

    assert(
      clientDemoRes.status === 200 && clientDemoData.success === true,
      "Demo Client API authentication succeeded",
      `Status: ${clientDemoRes.status}`
    );
    assert(
      clientDemoData.redirectUrl === "/dashboard",
      "Demo Client redirectUrl targets /dashboard",
      `Got: ${clientDemoData.redirectUrl}`
    );
    assert(
      clientCookies && clientCookies.includes("auth-token"),
      "Demo Client session cookies generated by SSR handler"
    );

    const lawyerDemoRes = await fetch(`${BASE_URL}/api/auth/demo-login`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ role: "lawyer" }),
    });
    const lawyerDemoData = await lawyerDemoRes.json();
    const lawyerCookies = lawyerDemoRes.headers.get("set-cookie");

    assert(
      lawyerDemoRes.status === 200 && lawyerDemoData.success === true,
      "Demo Lawyer API authentication succeeded",
      `Status: ${lawyerDemoRes.status}`
    );
    assert(
      lawyerDemoData.redirectUrl === "/lawyer/dashboard",
      "Demo Lawyer redirectUrl targets /lawyer/dashboard",
      `Got: ${lawyerDemoData.redirectUrl}`
    );
    assert(
      lawyerCookies && lawyerCookies.includes("auth-token"),
      "Demo Lawyer session cookies generated by SSR handler"
    );
  } catch (err) {
    assert(false, "Demo login API check failed", err.message);
  }

  // 3. Supabase Auth Verification (Genuine Passwords & User IDs)
  console.log("\n[Test 3/6] Testing Direct Supabase Auth Client Authentication...");
  const clientSupabase = createClient(SUPABASE_URL, SUPABASE_ANON_KEY);
  let clientUser = null;
  try {
    const { data: authData, error: authErr } =
      await clientSupabase.auth.signInWithPassword({
        email: DEMO_CLIENT_EMAIL,
        password: DEMO_CLIENT_PASSWORD,
      });

    assert(!authErr && authData.user, "Demo Client signed in via Supabase Auth GoTrue", authErr?.message);
    clientUser = authData.user;
  } catch (err) {
    assert(false, "Demo client login exception", err.message);
  }

  const lawyerSupabase = createClient(SUPABASE_URL, SUPABASE_ANON_KEY);
  let lawyerUser = null;
  try {
    const { data: authData, error: authErr } =
      await lawyerSupabase.auth.signInWithPassword({
        email: DEMO_LAWYER_EMAIL,
        password: DEMO_LAWYER_PASSWORD,
      });

    assert(!authErr && authData.user, "Demo Lawyer signed in via Supabase Auth GoTrue", authErr?.message);
    lawyerUser = authData.user;
  } catch (err) {
    assert(false, "Demo lawyer login exception", err.message);
  }

  // 4. Role Verification in Database
  console.log("\n[Test 4/6] Verifying Database Roles in public.user_roles...");
  if (clientUser && lawyerUser) {
    const { data: clientRoles } = await clientSupabase
      .from("user_roles")
      .select("role")
      .eq("user_id", clientUser.id);

    const clientRoleList = clientRoles?.map((r) => r.role) || [];
    assert(
      clientRoleList.includes("client"),
      "Demo Client has 'client' role in public.user_roles",
      `Got: ${clientRoleList.join(",")}`
    );
    assert(
      !clientRoleList.includes("admin"),
      "Demo Client does NOT have 'admin' privileges"
    );

    const { data: lawyerRoles } = await lawyerSupabase
      .from("user_roles")
      .select("role")
      .eq("user_id", lawyerUser.id);

    const lawyerRoleList = lawyerRoles?.map((r) => r.role) || [];
    assert(
      lawyerRoleList.includes("lawyer"),
      "Demo Lawyer has 'lawyer' role in public.user_roles",
      `Got: ${lawyerRoleList.join(",")}`
    );
    assert(
      !lawyerRoleList.includes("admin"),
      "Demo Lawyer does NOT have 'admin' privileges"
    );
  }

  // 5. Row Level Security & Data Isolation Check
  console.log("\n[Test 5/6] Testing Row Level Security (RLS) Isolation...");
  if (clientUser && lawyerUser) {
    // Client queries their matters
    const { data: clientMatters, error: clientMattersErr } = await clientSupabase
      .from("legal_matters")
      .select("*");

    assert(
      !clientMattersErr && Array.isArray(clientMatters),
      "Demo Client can query their own legal matters under RLS",
      clientMattersErr?.message
    );

    const isAllClientOwned = clientMatters?.every(
      (m) => m.client_id === clientUser.id || m.assigned_lawyer_id === clientUser.id
    );
    assert(
      isAllClientOwned,
      "All matters returned to Demo Client are strictly owned by or assigned to Demo Client"
    );

    // Lawyer queries assigned consultation requests
    const { data: lawyerRequests, error: lawyerReqErr } = await lawyerSupabase
      .from("consultation_requests")
      .select("*");

    assert(
      !lawyerReqErr && Array.isArray(lawyerRequests),
      "Demo Lawyer can query assigned consultation requests under RLS",
      lawyerReqErr?.message
    );

    const isAllLawyerAssigned = lawyerRequests?.every(
      (r) => r.lawyer_id === lawyerUser.id || r.client_id === lawyerUser.id
    );
    assert(
      isAllLawyerAssigned,
      "All consultation requests returned to Demo Lawyer are strictly assigned to Demo Lawyer"
    );
  }

  // 6. Demo Lawyer Verification & Publication Status (Not Publicly Listed)
  console.log("\n[Test 6/6] Verifying Demo Lawyer Verification Status & Directory Concealment...");
  if (lawyerUser) {
    const { data: lawyerProfile } = await lawyerSupabase
      .from("lawyer_profiles")
      .select("is_published, bar_council_number")
      .eq("id", lawyerUser.id)
      .single();

    assert(
      lawyerProfile?.is_published === false,
      "Demo Lawyer has is_published = false (not published to public directory)",
      `is_published: ${lawyerProfile?.is_published}`
    );

    const { data: publicDirectoryListing } = await clientSupabase
      .from("public_lawyer_directory")
      .select("id")
      .eq("id", lawyerUser.id);

    assert(
      !publicDirectoryListing || publicDirectoryListing.length === 0,
      "Demo Lawyer is excluded from public.public_lawyer_directory (Rule 36 compliance)"
    );
  }

  console.log("\n======================================================================");
  console.log(`TEST SUITE RESULTS: ${passed} PASSED, ${failed} FAILED`);
  console.log("======================================================================");

  if (failed > 0) {
    process.exit(1);
  }
}

runPortalTests().catch((e) => {
  console.error("Test Suite Fatal Error:", e);
  process.exit(1);
});
